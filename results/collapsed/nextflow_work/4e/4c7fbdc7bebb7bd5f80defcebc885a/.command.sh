#!/usr/bin/env bash -exuo pipefail
mkdir -p tmp/asncache
prime_cache -cache tmp/asncache/ -ifmt asnb-seq-entry  -i gnomon_wnode.out -oseq-ids spids1 -split-sequences
prime_cache -cache tmp/asncache/ -ifmt asn-seq-entry  -i DO2_collapsed_polished.asn -oseq-ids spids2 -split-sequences
if [[ -n "7586.proteins.asn" ]]; then
    if [[ `head -c4 7586.proteins.asn` == "Seq-" ]]; then
        prime_cache -cache tmp/asncache/ -ifmt asn-seq-entry -i 7586.proteins.asn -oseq-ids spids3 #-split-sequences
    else
        prime_cache -cache tmp/asncache/ -ifmt asnb-seq-entry -i 7586.proteins.asn -oseq-ids spids3 #-split-sequences
    fi
fi

filename=$(basename -- "job.000")
extension="${filename##*.}"
(( start_job_id = ((10#$extension) * 2051) + 1 ))

# Slices generated by gnomon_wnode and chainer_wnode are relative to files where they were when they're produced by gpx_qdump
# We need to make these filenames relative to imported models
rm -f input_slices.mft
for f in evidence.1.out.gz.slices gnomon_wnode.out.slices exon.1.out.gz.slices ; do
    basename `head -1 $f` >${f}_true
    tail -n +2 $f >>${f}_true
    echo "${f}_true" >> input_slices.mft
done
mkdir -p tmp/interim
gnomon_report -exclusive-threshold 800000000 -max-splice-diff 5 -nogenbank -egapx  -input-slices input_slices.mft -asn-cache tmp/asncache/  -start-job-id $start_job_id -workers 8 -input-jobs job.000 -O tmp/interim

mkdir -p output
cat tmp/interim/* > output/gnomon_report.1.gpx-job.asnb
rm -rf tmp
